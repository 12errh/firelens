@app.get("/api/investigations", tags=["investigations"])
def list_investigations(
    q: str | None = Query(None, description="Free-text search over record metadata."),
    kind: Literal["flight", "ground", "analysis"] | None = None,
    gravity: str | None = Query(None, description="microgravity, normal_gravity, ..."),
    phase: Literal["solid", "liquid", "gas", "aerosol"] | None = None,
    has_o2: bool | None = Query(None, alias="hasO2"),
    limit: int = Query(100, ge=1, le=200),
    offset: int = Query(0, ge=0),
) -> dict[str, Any]:
    """List normalized investigations with optional filters."""
    rows = [record for record in INVESTIGATIONS if matches(record, q or "")]
    if kind:
        rows = [record for record in rows if record.get("kind") == kind]
    if gravity:
        rows = [record for record in rows if record.get("gravity") == gravity]
    if phase:
        rows = [
            record
            for record in rows
            if any(table.get("phase") == phase for table in record.get("tables", []))
        ]
    if has_o2 is not None:
        rows = [record for record in rows if (o2_summary(record) is not None) == has_o2]
    total = len(rows)
    page = rows[offset : offset + limit]
    return {
        "total": total,
        "limit": limit,
        "offset": offset,
        "items": [compact(record) for record in page],
    }


@app.get("/api/investigations/{investigation_id}", tags=["investigations"])
def get_investigation(investigation_id: str) -> dict[str, Any]:
    """One full record plus its evidence points, documents, and license."""
    record = BY_ID.get(investigation_id.upper())
    if not record:
        raise HTTPException(status_code=404, detail="Investigation not found.")
    return {
        "investigation": record,
        "evidence": EVIDENCE_BY_ID.get(record["id"], []),
        "documents": DOCUMENTS_BY_ID.get(record["id"], []),
        "scenarios": [
            scenario
            for scenario in SCENARIOS
            if record["id"] in scenario.get("evidence", [])
        ],
    }


@app.get("/api/evidence", tags=["evidence"])
def list_evidence(
    phase: Literal["solid", "liquid", "gas", "aerosol"] | None = None,
    gravity: str | None = None,
    min_o2: float | None = Query(None, ge=0, le=100, alias="minO2"),
    at_or_above_30: bool | None = Query(None, alias="atOrAbove30"),
) -> dict[str, Any]:
    """The 14 normalized evidence points, filterable by phase, gravity, oxygen."""
    rows = list(EVIDENCE)
    if phase:
        rows = [point for point in rows if point.get("phase") == phase]
    if gravity:
        rows = [point for point in rows if point.get("gravity") == gravity]
    if min_o2 is not None:
        rows = [
            point
            for point in rows
            if point.get("o2") and point["o2"]["max"] >= min_o2
        ]
    if at_or_above_30 is not None:
        rows = [
            point
            for point in rows
            if (bool(point.get("o2")) and point["o2"]["max"] >= 30) == at_or_above_30
        ]
    return {
        "total": len(rows),
        "items": rows,
        "partialGravityDatasets": STATS.get("partialGravityDatasets", 0),
    }


@app.get("/api/search", tags=["discovery"])
def search(
    q: str = Query(..., min_length=1, description="Search term or PSI accession."),
    limit: int = Query(10, ge=1, le=50),
) -> dict[str, Any]:
    """Search investigations, evidence points, and indexed documents."""
    needle = q.lower().strip()
    records = [record for record in INVESTIGATIONS if matches(record, needle)][:limit]
    points = [
        point
        for point in EVIDENCE
        if needle
        in " ".join(
            str(point.get(key) or "")
            for key in ("label", "shortLabel", "fuel", "phase", "investigationId")
        ).lower()
    ][:limit]
    docs = [
        doc
        for doc in DOCUMENTS
        if needle
        in " ".join(str(doc.get(key) or "") for key in ("title", "fileName", "path")).lower()
    ][:limit]
    return {
        "query": q,
        "investigations": {"total": len(records), "items": [compact(r) for r in records]},
        "evidence": {"total": len(points), "items": points},
        "documents": {"total": len(docs), "items": docs},
    }


class CompareRequest(BaseModel):
    ids: list[str] = Field(
        ...,
        min_length=2,
        max_length=4,
        description="Two to four PSI accessions, for example [\"PSI-25\", \"PSI-99\"].",
    )


@app.post("/api/compare", tags=["investigations"])
def compare(payload: CompareRequest) -> dict[str, Any]:
    """Place two to four records side by side without inferring missing values."""
    records = []
    missing = []
    for raw_id in payload.ids:
        record = BY_ID.get(raw_id.upper())
        if record:
            records.append(
                {
                    "id": record["id"],
                    "title": record.get("title"),
                    "acronym": record.get("acronym"),
                    "kind": record.get("kind"),
                    "gravity": record.get("gravity"),
                    "subResearchArea": record.get("subResearchArea"),
                    "o2": o2_summary(record),
                    "tableCount": record.get("tableCount", 0),
                    "publicationCount": record.get("publicationCount", 0),
                    "doi": record.get("doi"),
                    "license": record.get("license"),
                    "evidence": EVIDENCE_BY_ID.get(record["id"], []),
                }
            )
        else:
            missing.append(raw_id)
    if not records:
        raise HTTPException(status_code=404, detail="None of the requested records exist.")
    return {
        "requested": payload.ids,
        "missing": missing,
        "records": records,
        "note": (
            "A missing oxygen value is reported as null, not zero. "
            "Only SAFFIRE-II provides a 1 g comparison; it is not a gravity matrix."
        ),
    }


@app.get("/api/insights", tags=["evidence"])
def insights(kind: str | None = Query(None, description="gap, finding, or method.")) -> dict[str, Any]:
    """Computed findings and explicit gaps behind the interface."""
    rows = [insight for insight in INSIGHTS if not kind or insight.get("kind") == kind]
    return {"total": len(rows), "items": rows}


@app.get("/api/scenarios", tags=["evidence"])
def scenarios() -> dict[str, Any]:
    """Spacecraft, lunar, and Mars readiness classifications."""
    return {"total": len(SCENARIOS), "items": SCENARIOS}


class ChatRequest(BaseModel):
    message: str = Field(..., min_length=1, max_length=800)
    question: str | None = None


@app.post("/api/chat", tags=["assistant"])
async def chat(payload: ChatRequest) -> dict[str, Any]:
    """Proxy to the optional document-RAG endpoint.

    The public web app also ships a deterministic answer engine at
    ``/api/chat``; this endpoint only forwards to a configured RAG service so
    the Python API never fabricates an answer of its own.
    """
    url = os.environ.get("RAG_API_URL")
    if not url:
        raise HTTPException(
            status_code=503,
            detail=(
                "No document-RAG endpoint configured. Set RAG_API_URL, or use the "
                "web app's /api/chat endpoint for the deterministic evidence answer."
            ),
        )
    headers = {"Content-Type": "application/json"}
    key = os.environ.get("RAG_API_KEY")
    if key:
        headers["Authorization"] = f"Bearer {key}"
    body = {
        "question": payload.question or payload.message,
        "query": payload.question or payload.message,
    }
    try:
        async with httpx.AsyncClient(timeout=45) as client:
            response = await client.post(url, json=body, headers=headers)
    except httpx.HTTPError as exc:
        raise HTTPException(status_code=502, detail=f"RAG request failed: {exc}") from exc
    if response.status_code >= 400:
        raise HTTPException(
            status_code=502,
            detail=f"RAG endpoint returned {response.status_code}.",
        )
    data = response.json()
    data.setdefault("mode", "rag")
    return data