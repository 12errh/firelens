"""Flame in Freefall — read-only evidence API.

Serves the normalized NASA PSI combustion snapshot that powers the Next.js
workbench. The canonical dataset lives in ``web/data`` and is generated by
``ingest/build_dataset.py``. This service does not scrape PSI at request time
and never fills a missing value.

Run locally:
    uvicorn api.main:app --reload --port 8000

Environment:
    DATA_DIR            Path to the generated JSON directory.
    ALLOWED_ORIGINS     Comma-separated browser origins.
    RAG_API_URL         Optional document-RAG endpoint for /api/chat.
    RAG_API_KEY         Optional bearer token for the RAG endpoint.
"""

from __future__ import annotations

import json
import os
from functools import lru_cache
from pathlib import Path
from typing import Any, Literal

import httpx
from fastapi import FastAPI, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = Path(os.environ.get("DATA_DIR", ROOT / "web" / "data"))
# Vercel deployments use `api/` as the project root and copy the snapshot beside main.py.
if not DATA_DIR.exists():
    local_snapshot = Path(__file__).resolve().parent / "data"
    if local_snapshot.exists():
        DATA_DIR = local_snapshot
SNAPSHOT_FILES = {
    "investigations": "investigations.json",
    "evidence": "evidence_points.json",
    "documents": "documents.json",
    "stats": "stats.json",
    "insights": "insights.json",
    "scenarios": "scenarios.json",
    "manifest": "manifest.json",
}

SERVICE = {
    "name": "Flame in Freefall evidence API",
    "version": "1.0.0",
    "source": "NASA Physical Sciences Informatics (PSI)",
    "disclaimer": "Independent project. Not affiliated with or endorsed by NASA.",
    "docs": "/docs",
}


@lru_cache(maxsize=None)
def load(name: str) -> Any:
    """Load one snapshot file once. The snapshot is immutable per process."""
    path = DATA_DIR / SNAPSHOT_FILES[name]
    if not path.exists():
        raise RuntimeError(
            f"Snapshot file {path} is missing. Run ingest/build_dataset.py first."
        )
    return json.loads(path.read_text(encoding="utf-8"))


INVESTIGATIONS: list[dict[str, Any]] = load("investigations")
EVIDENCE: list[dict[str, Any]] = load("evidence")
DOCUMENTS: list[dict[str, Any]] = load("documents")
STATS: dict[str, Any] = load("stats")
INSIGHTS: list[dict[str, Any]] = load("insights")
SCENARIOS: list[dict[str, Any]] = load("scenarios")
MANIFEST: dict[str, Any] = load("manifest")

BY_ID = {record["id"]: record for record in INVESTIGATIONS}
EVIDENCE_BY_ID: dict[str, list[dict[str, Any]]] = {}
for _point in EVIDENCE:
    EVIDENCE_BY_ID.setdefault(_point["investigationId"], []).append(_point)
DOCUMENTS_BY_ID: dict[str, list[dict[str, Any]]] = {}
for _doc in DOCUMENTS:
    DOCUMENTS_BY_ID.setdefault(_doc["investigationId"], []).append(_doc)

app = FastAPI(
    title=SERVICE["name"],
    version=SERVICE["version"],
    description=(
        "Read-only access to 24 normalized NASA PSI Combustion Science "
        "investigations, 22 experimental summary tables, and 14 evidence points. "
        "Missing values are null; they are never invented."
    ),
    license_info={"name": "CC0 1.0 for most records; see per-record license"},
)

default_origins = "http://localhost:3000,http://127.0.0.1:3000"
origins = [
    origin.strip()
    for origin in os.environ.get("ALLOWED_ORIGINS", default_origins).split(",")
    if origin.strip()
]
app.add_middleware(
    CORSMiddleware,
    allow_origins=origins,
    allow_origin_regex=r"https://[a-z0-9-]+\.vercel\.app",
    allow_credentials=False,
    allow_methods=["GET", "POST", "OPTIONS"],
    allow_headers=["*"],
)


def o2_summary(record: dict[str, Any]) -> dict[str, Any] | None:
    points = [
        point
        for point in EVIDENCE_BY_ID.get(record["id"], [])
        if point.get("o2")
    ]
    if not points:
        return None
    return {
        "min": min(point["o2"]["min"] for point in points),
        "max": max(point["o2"]["max"] for point in points),
        "n": sum(point["o2"]["n"] for point in points),
        "approximate": any(point["o2"].get("approximate") for point in points),
        "unit": "%",
    }


def compact(record: dict[str, Any]) -> dict[str, Any]:
    phases = sorted(
        {
            table.get("phase")
            for table in record.get("tables", [])
            if table.get("phase")
        }
    )
    return {
        "id": record["id"],
        "accession": record.get("accession"),
        "title": record.get("title"),
        "acronym": record.get("acronym"),
        "kind": record.get("kind"),
        "kindLabel": record.get("kindLabel"),
        "gravity": record.get("gravity"),
        "analog": record.get("analog", False),
        "subResearchArea": record.get("subResearchArea"),
        "summary": record.get("summary"),
        "o2": o2_summary(record),
        "phases": phases,
        "tableCount": record.get("tableCount", 0),
        "publicationCount": record.get("publicationCount", 0),
        "doi": record.get("doi"),
        "image": record.get("image"),
    }


def matches(record: dict[str, Any], query: str) -> bool:
    needle = query.lower().strip()
    if not needle:
        return True
    haystack = " ".join(
        str(value)
        for value in (
            record.get("id"),
            record.get("title"),
            record.get("acronym"),
            record.get("summary"),
            record.get("objective"),
            record.get("subResearchArea"),
            record.get("hardware"),
            " ".join(
                str(item)
                for table in record.get("tables", [])
                for item in [table.get("name"), *table.get("fuelValues", [])]
            ),
        )
        if value
    ).lower()
    return all(token in haystack for token in needle.split())


@app.get("/", include_in_schema=False)
def root() -> dict[str, Any]:
    return {**SERVICE, "endpoints": sorted(app.openapi()["paths"].keys())}


